/*
 * The vendor's NCT6686D setup, copied write for write from the table NCT6686DPeiInit replays
 * (3.40 image, 0xffeebcac). A non-zero mask keeps those bits of the register's current value.
 * CR1B bit 3 is the one that matters for bring-up: it turns pin 34 into SOUTA_P80, the PORT80
 * UART output that the UART1 header carries (NCT6686D datasheet 0.5, CR 1Bh). Its default is
 * 0x10, which leaves pin 34 as GPIO25. The PORT80 UART itself (LDN 8) is enabled at 115200 by
 * default.
 */
static const struct {
	uint16_t port;
	uint8_t mask;
	uint8_t value;
} sio_table[] = {
	{ 0x2e, 0x00, 0x87 }, { 0x2e, 0x00, 0x87 },	/* enter configuration mode */
	{ 0x2e, 0x00, 0x10 }, { 0x2f, 0x00, 0x00 },	/* global registers */
	{ 0x2e, 0x00, 0x11 }, { 0x2f, 0x7c, 0x00 },
	{ 0x2e, 0x00, 0x1d }, { 0x2f, 0xf7, 0x08 },
	{ 0x2e, 0x00, 0x13 }, { 0x2f, 0x00, 0x00 },
	{ 0x2e, 0x00, 0x14 }, { 0x2f, 0x00, 0x00 },
	{ 0x2e, 0x00, 0x1b }, { 0x2f, 0xf7, 0x08 },	/* pin 34 = SOUTA_P80 */
	{ 0x2e, 0x00, 0x27 }, { 0x2f, 0x3f, 0x00 },
	{ 0x2e, 0x00, 0x29 }, { 0x2f, 0xe7, 0x18 },
	{ 0x2e, 0x00, 0x07 }, { 0x2f, 0x00, 0x0b },	/* LDN 0x0b, EC: base 0x0a20, active */
	{ 0x2e, 0x00, 0x61 }, { 0x2f, 0x00, 0x20 },
	{ 0x2e, 0x00, 0x60 }, { 0x2f, 0x00, 0x0a },
	{ 0x2e, 0x00, 0x30 }, { 0x2f, 0x00, 0x01 },
	{ 0x2e, 0x00, 0x07 }, { 0x2f, 0x00, 0x01 },	/* LDN 1: inactive */
	{ 0x2e, 0x00, 0x30 }, { 0x2f, 0x00, 0x00 },
	{ 0x2e, 0x00, 0x07 }, { 0x2f, 0x00, 0x02 },	/* LDN 2, UART A: inactive */
	{ 0x2e, 0x00, 0x30 }, { 0x2f, 0x00, 0x00 },
	{ 0x2e, 0x00, 0x07 }, { 0x2f, 0x00, 0x03 },	/* LDN 3: inactive */
	{ 0x2e, 0x00, 0x30 }, { 0x2f, 0x00, 0x00 },
	{ 0x2e, 0x00, 0x07 }, { 0x2f, 0x00, 0x05 },	/* LDN 5, KBC: 0x60/0x64, IRQ 1 */
	{ 0x2e, 0x00, 0x60 }, { 0x2f, 0x00, 0x00 },
	{ 0x2e, 0x00, 0x61 }, { 0x2f, 0x00, 0x60 },
	{ 0x2e, 0x00, 0x62 }, { 0x2f, 0x00, 0x00 },
	{ 0x2e, 0x00, 0x63 }, { 0x2f, 0x00, 0x64 },
	{ 0x2e, 0x00, 0x70 }, { 0x2f, 0x00, 0x01 },
	{ 0x2e, 0x00, 0x30 }, { 0x2f, 0x00, 0x01 },
	{ 0x2e, 0x00, 0x07 }, { 0x2f, 0x00, 0x0d },	/* LDN 0x0d */
	{ 0x2e, 0x00, 0xf3 }, { 0x2f, 0xf1, 0x00 },
	{ 0x2e, 0x00, 0x07 }, { 0x2f, 0x00, 0x0f },	/* LDN 0x0f */
	{ 0x2e, 0x00, 0xea }, { 0x2f, 0xfe, 0x01 },
	{ 0x2e, 0x00, 0xaa },				/* leave configuration mode */
};

/* EC register access through the EC logical device at 0xa20, page and index as the vendor's. */
#define EC_PAGE		0xa20
#define EC_INDEX	0xa21
#define EC_DATA		0xa22

/* One Super I/O register write in its own configuration mode session, like the vendor's. */
static void sio_write(uint8_t reg, uint8_t value)
{
	outb(0x87, 0x2e);
	outb(0x87, 0x2e);
	outb(reg, 0x2e);
	outb(value, 0x2f);
	outb(0xaa, 0x2e);
}

/* The vendor's EC accessors select LDN 0x0b and reprogram it before every access. */
static void ec_select(void)
{
	sio_write(0x07, 0x0b);
	sio_write(0x30, 0x01);
	sio_write(0x60, 0x0a);
	sio_write(0x61, 0x20);
}

static uint8_t ec_read(uint8_t page, uint8_t index)
{
	uint8_t value;

	ec_select();
	outb(0xff, EC_PAGE);
	outb(page, EC_PAGE);
	outb(index, EC_INDEX);
	value = inb(EC_DATA);
	outb(0xff, EC_PAGE);
	return value;
}

static void ec_write(uint8_t page, uint8_t index, uint8_t value)
{
	ec_select();
	outb(0xff, EC_PAGE);
	outb(page, EC_PAGE);
	outb(index, EC_INDEX);
	outb(value, EC_DATA);
	outb(0xff, EC_PAGE);
}

/*
 * What NCT6686DPeiInit does after the table, before the vendor's first POST code that reaches
 * the UART1 header: a KBC self test, then EC writes whose meaning is not documented in the
 * datasheet. The vendor waits 10 ms (35800 ACPI timer ticks) between the two groups.
 */
static void vendor_ec_init(void)
{
	if (inb(0x64) != 0xff) {
		outb(0xaa, 0x64);
		for (unsigned int i = 0; i < 256; i++) {
			if (!(inb(0x64) & 0x02))
				break;
		}
	}

	ec_write(5, 0x60, ec_read(5, 0x60) | 0x80);
	ec_write(4, 0x61, 0x02);
	ec_write(4, 0x62, 0x03);
	mdelay(10);
	ec_write(2, 0x40, ec_read(2, 0x40) & 0xf8);
	ec_write(2, 0x41, ec_read(2, 0x41) & 0xfe);
	ec_write(2, 0x42, 0x00);
}

void bootblock_mainboard_early_init(void)
{
	for (size_t i = 0; i < ARRAY_SIZE(sio_table); i++) {
		uint8_t value = sio_table[i].value;

		if (sio_table[i].mask)
			value |= inb(sio_table[i].port) & sio_table[i].mask;
		outb(value, sio_table[i].port);
	}

	vendor_ec_init();
}

void bootblock_mainboard_init(void)
{
	gpio_configure_pads(early_gpio_table, early_gpio_table_size);

	/* The chipset's pads are reached through its P2SB, which must be visible here. */
	gpio_configure_pads(pch_gpio_table, pch_gpio_table_size);
}
